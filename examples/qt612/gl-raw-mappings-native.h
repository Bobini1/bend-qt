#ifdef BQT_RAW_MAPPING_MAP
static void gl_raw_mapping_checks()
{
    using namespace bendqt;
    QOpenGLContext context;
    QSurfaceFormat format;
    format.setVersion(3, 2);
    format.setProfile(QSurfaceFormat::CoreProfile);
    context.setFormat(format);
    assert(context.create());
    QOffscreenSurface surface;
    surface.setFormat(context.format());
    surface.create();
    assert(context.makeCurrent(&surface));
    BqtRequest request{};
    auto functions = own(&request, new QOpenGLFunctions_3_2_Core, BQT_RAW_MAPPING_FUNCTIONS_TYPE);
    assert(functions && !request.error);
    auto *gl = context.extraFunctions();
    GLuint buffer = 0;
    gl->glGenBuffers(1, &buffer);
    gl->glBindBuffer(GL_ARRAY_BUFFER, buffer);
    gl->glBufferData(GL_ARRAY_BUFFER, 8, "abcdefgh", GL_DYNAMIC_DRAW);
    auto call = [&](auto operation, uint32_t self) {
        request = {}; request.self = self;
        operation(&request);
    };
    auto release = [&](uint32_t id) {
        call(destroy_object, id);
        assert(!request.error);
    };
    auto map = [&](GLenum access) {
        request = {}; request.self = functions;
        request.arguments[0].word = GL_ARRAY_BUFFER;
        request.arguments[1].word = access;
        BQT_RAW_MAPPING_MAP(&request);
        assert(!request.error && request.result.word);
        return request.result.word;
    };
    auto read = [&](uint32_t view, uint64_t offset, uint64_t length) {
        request = {}; request.self = view;
        request.arguments[0] = wide_value(offset);
        request.arguments[1] = wide_value(length);
        BQT_RAW_MAPPING_READ(&request);
        discard_value(request.arguments[0]); discard_value(request.arguments[1]);
        return request.result.word;
    };
    const auto first = map(GL_READ_WRITE);
    call(BQT_RAW_MAPPING_SIZE, first);
    assert(!request.error && wide_bits(request.result) == 8);
    discard_value(request.result);
    auto data = read(first, 0, 8);
    assert(!request.error && *static_cast<QByteArray *>(entry(data)->value) == "abcdefgh");
    release(data);
    read(first, 7, 2);
    assert(request.error == ERANGE);
    request = {}; request.self = functions;
    request.arguments[0].word = GL_ARRAY_BUFFER;
    request.arguments[1].word = GL_BUFFER_MAP_POINTER;
    BQT_RAW_MAPPING_GET(&request);
    assert(!request.error && request.result.word);
    const auto alias = request.result.word;
    assert(static_cast<MemoryView *>(entry(alias)->value)->raw_gl_mapping == static_cast<MemoryView *>(entry(first)->value)->raw_gl_mapping);
    request = {}; request.self = functions;
    request.arguments[0].word = 1;
    request.arguments[1] = sequence_value(1);
    request.arguments[1].items[0].word = buffer;
    BQT_RAW_MAPPING_DELETE(&request);
    assert(request.error == EBUSY && gl->glIsBuffer(buffer));
    discard_value(request.arguments[1]);
    call(destroy_object, functions);
    assert(request.error == EBUSY);
    release(first);
    GLint mapped = 0;
    gl->glGetBufferParameteriv(GL_ARRAY_BUFFER, GL_BUFFER_MAPPED, &mapped);
    assert(mapped);
    data = read(alias, 0, 8);
    assert(!request.error);
    release(data);
    release(alias);
    gl->glGetBufferParameteriv(GL_ARRAY_BUFFER, GL_BUFFER_MAPPED, &mapped);
    assert(!mapped);

    const auto readonly = map(GL_READ_ONLY);
    request = {};
    const auto bytes = own(&request, new QByteArray("XY"), BQT_GL_BYTE_ARRAY_TYPE);
    request = {}; request.self = readonly;
    request.arguments[0] = wide_value(0);
    request.arguments[1].word = bytes;
    BQT_RAW_MAPPING_WRITE(&request);
    assert(request.error == EPERM);
    discard_value(request.arguments[0]);
    release(readonly);
    request = {}; request.self = functions;
    request.arguments[0].word = GL_ARRAY_BUFFER;
    request.arguments[1] = wide_value(2); request.arguments[2] = wide_value(4);
    request.arguments[3].word = GL_MAP_WRITE_BIT | GL_MAP_FLUSH_EXPLICIT_BIT;
    BQT_RAW_MAPPING_RANGE(&request);
    assert(!request.error);
    const auto writeonly = request.result.word;
    discard_value(request.arguments[1]); discard_value(request.arguments[2]);
    read(writeonly, 0, 2);
    assert(request.error == EPERM);
    request = {}; request.self = writeonly;
    request.arguments[0] = wide_value(0); request.arguments[1].word = bytes;
    BQT_RAW_MAPPING_WRITE(&request);
    assert(!request.error);
    discard_value(request.arguments[0]);
    release(writeonly);
    release(bytes);
    const auto modified = map(GL_READ_ONLY);
    data = read(modified, 0, 8);
    assert(!request.error && *static_cast<QByteArray *>(entry(data)->value) == "abXYefgh");
    release(data);
    request = {}; request.self = functions;
    request.arguments[0].word = GL_ARRAY_BUFFER;
    BQT_RAW_MAPPING_UNMAP(&request);
    assert(!request.error && request.result.word);
    call(BQT_RAW_MAPPING_SIZE, modified);
    assert(request.error == ESTALE);
    release(modified);
    request = {}; request.self = functions;
    request.arguments[0].word = GL_ARRAY_BUFFER;
    request.arguments[1] = wide_value(7); request.arguments[2] = wide_value(2);
    request.arguments[3].word = GL_MAP_READ_BIT;
    BQT_RAW_MAPPING_RANGE(&request);
    assert(request.error == ERANGE);
    discard_value(request.arguments[1]); discard_value(request.arguments[2]);
    gl->glGetBufferParameteriv(GL_ARRAY_BUFFER, GL_BUFFER_MAPPED, &mapped);
    assert(!mapped);
    gl->glDeleteBuffers(1, &buffer);
    release(functions);
    std::puts("QT612_NATIVE_GL_RAW_MAPPING_OK map_extent=1 getter_alias=1 last_scope_unmaps=1 guarded_delete=1 read_write_access=1 explicit_flush=1 explicit_unmap_stale=1 bounds=1");
}
#endif
