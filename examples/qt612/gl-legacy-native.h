#ifdef BQT_LEGACY_MATERIAL_SET
static void gl_legacy_checks()
{
    using namespace bendqt;
    QOpenGLContext context;
    assert(context.create());
    QOffscreenSurface surface;
    surface.setFormat(context.format());
    surface.create();
    assert(context.makeCurrent(&surface));
    BqtRequest request{};
    const auto id = own(&request, new QOpenGLFunctions_1_0, BQT_GL_LEGACY_FUNCTIONS_TYPE);
    assert(id && !request.error);
    auto values = [](std::initializer_list<double> input) {
        auto result = sequence_value(input.size());
        size_t i = 0;
        for (double value : input) result.items[i++] = real_bits(value);
        return result;
    };
    request = {};
    request.self = id;
    request.arguments[0].word = GL_FRONT;
    request.arguments[1].word = GL_DIFFUSE;
    request.arguments[2] = values({0.25, 0.5, 0.75, 1});
    BQT_LEGACY_MATERIAL_SET(&request);
    assert(!request.error);
    BQT_LEGACY_MATERIAL_GET(&request);
    assert(!request.error && request.result.count == 1 && request.result.items[0].count == 4);
    assert(real_value(request.result.items[0].items[1]) == 0.5);
    discard_value(request.result);
    discard_value(request.arguments[2]);
    request.arguments[2] = values({0.25, 0.5});
    BQT_LEGACY_MATERIAL_GET(&request);
    assert(request.error == ERANGE);
    discard_value(request.arguments[2]);
    request = {};
    request.self = id;
    request.arguments[0].word = GL_MAP1_VERTEX_3;
    request.arguments[1] = real_bits(0);
    request.arguments[2] = real_bits(1);
    request.arguments[3].word = 3;
    request.arguments[4].word = 2;
    request.arguments[5] = values({0, 0, 0, 1, 2, 3});
    BQT_LEGACY_MAP_SET(&request);
    assert(!request.error);
    discard_value(request.arguments[1]);
    discard_value(request.arguments[2]);
    discard_value(request.arguments[5]);
    request = {};
    request.self = id;
    request.arguments[0].word = GL_MAP1_VERTEX_3;
    request.arguments[1].word = GL_COEFF;
    request.arguments[2] = values({0, 0, 0, 0, 0});
    BQT_LEGACY_MAP_GET(&request);
    assert(request.error == ERANGE);
    discard_value(request.arguments[2]);
    request.error = 0;
    request.arguments[2] = values({0, 0, 0, 0, 0, 0});
    BQT_LEGACY_MAP_GET(&request);
    assert(!request.error && request.result.items[0].count == 6);
    assert(real_value(request.result.items[0].items[5]) == 3);
    discard_value(request.arguments[2]);
    discard_value(request.result);
    context.functions()->glPixelStorei(GL_PACK_SKIP_ROWS, 1);
    request = {};
    auto *storage = new QByteArray(128, char(0));
    const auto bytes = own(&request, storage, BQT_GL_BYTE_ARRAY_TYPE);
    request = {};
    request.self = id;
    request.arguments[0].word = bytes;
    BQT_LEGACY_STIPPLE_GET(&request);
    assert(request.error == ERANGE);
    storage->resize(132);
    request.error = 0;
    BQT_LEGACY_STIPPLE_GET(&request);
    assert(!request.error && storage->at(4) == char(0xff));
    context.functions()->glPixelStorei(GL_PACK_SKIP_ROWS, 0);
    request = {};
    request.self = bytes;
    destroy_object(&request);
    assert(!request.error);
    request = {};
    request.self = id;
    destroy_object(&request);
    assert(!request.error);
    std::puts("QT612_NATIVE_GL_LEGACY_OK selector_extent=1 native_material=1 evaluator_stride=1 queried_order=1 short_output_rejected=1 stipple_pixel_layout=1");
}
#endif
